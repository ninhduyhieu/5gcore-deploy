func (t *Tunnel) createDefaultPath() (err error) {
	if t.defaultPath != nil {
		return
	}
	//check if we can pick one of the existing path as default
	for _, path := range t.paths {
		if canBeDefault(path.pcc) {
			t.Infof("Datapath %d is used as default path", path.id)
			t.setDefaultPath(path)
			return
		}
	}
	var upfPath topo.UpfPath
	if upfPath, err = t.findUpfPath(nil); err != nil { //find path without traffic control data
		err = utils.WrapError("Find Upf Path to create a default path", err)
		return
	}

	var path *Path
	if path, err = t.createPath(upfPath); err != nil {
		err = utils.WrapError("Create default datapath", err)
		return
	}
	t.Infof("Create datapath %d to used as default path", path.id)
	t.setDefaultPath(path)
	return
}

