func (t *Tunnel) HandleSmPolicyDecision(pol *models.SmPolicyDecision) (err error) {

	updateDefaultQos := t.defaultPath == nil //need to add/update default Qos

	//handle TrafficControlData
	for id, dat := range pol.TraffContDecs {
		t.Tracef("Handle Traffic control description %s", id)
		if dat == nil { //to delete
			delete(t.trafficControlDataMap, id)
		} else { //update or create new TrafficControlData
			dat.TcId = id
			t.trafficControlDataMap[dat.TcId] = *dat
		}
	}

	//handle PccRules
	for id, rule := range pol.PccRules {
		t.Tracef("Handle Pcc rule %s", id)
		if rule == nil {
			t.deletePccRule(id)
		} else {
			//create a new datapath or update an existing one
			rule.PccRuleId = id
			t.updatePccRule(rule)
		}
	}

	//make sure to have a default datapath
	if err = t.createDefaultPath(); err != nil {
		err = utils.WrapError("Pick/create a default path", err)
		return
	}

	//handle Session Rules
	for id, rule := range pol.SessRules {
		t.Tracef("Handle session rule %s", id)
		if rule == nil { //delete a session rule
			if _, ok := t.sessionRules[id]; ok {
				delete(t.sessionRules, id)
				if id == t.selectedSessionRule { //if current selected session rule is delete
					updateDefaultQos = true
				}
			}
		} else { //update or create new session rule
			rule.SessRuleId = id
			if _, ok := t.sessionRules[id]; ok { //rule existed
				t.sessionRules[rule.SessRuleId] = rule
				//if updated session rule is the selected one, need to update
				//default Qos for the UPFs on the default path
				if id == t.selectedSessionRule {
					updateDefaultQos = true
				}
			} else { //add the new session rule
				t.sessionRules[id] = rule
				//pick a selected session rule
				if len(t.selectedSessionRule) == 0 {
					t.selectedSessionRule = id
				}
			}
		}
	}

	if updateDefaultQos {
		t.updateDefaultQos() //create or update QERs for default path
	}

	//3. handle QosData
	for id, dat := range pol.QosDecs {
		t.Tracef("Handle Qos description %s", id)
		if dat == nil { //to delete
			t.deleteQosFlow(id)
		} else { //update or create new QosFlow
			dat.QosId = id
			t.updateQosFlow(dat)
		}
	}

	//4. assign Qos flow for data path
	for id, rule := range pol.PccRules {
		if path, ok := t.paths[id]; ok && path.qosFlow == nil {
			if qosFlow := t.pickQosFlow(rule); qosFlow != nil {
				path.setQosFlow(qosFlow)
			} else {
				//TODO: cancel transactions
				err = fmt.Errorf("Pcc %s has no Qos flow", id)
				return
			}
		}
	}

	//5. create PDRs and related rules for new created data paths
	if err = t.defaultPath.createPDRs(t); err != nil {
		err = utils.WrapError("Create PDRs for default data path", err)
		//TODO: cancel transactions
		return
	}

	for _, path := range t.paths {
		if err = path.createPDRs(t); err != nil {
			err = utils.WrapError("Create PDRs for data path", err)
			//TODO: cancel transactions
			return
		}
	}

	//ask UPFs to execute all pending transactions
	if err = t.updateUPFs(nil); err != nil {
		err = utils.WrapError("Update sessions at UPFs", err)
	}
	return
}

func (t *Tunnel) updateDefaultQos() {
	t.Tracef("Update default Qos flow")
	var rule *models.SessionRule
	if len(t.selectedSessionRule) > 0 {
		rule, _ = t.sessionRules[t.selectedSessionRule]
	}
	//update default Qos Flow for the default Path
	t.defaultPath.setQosFlow(newDefaultQosFlow(rule))
}

func (t *Tunnel) deletePccRule(id string) {
	if path, ok := t.paths[id]; ok {
		delete(t.paths, id)
		t.freePrecedence(path.precedence)
		if !t.isDefaultPath(path) { //don't remove default path
			path.deleteRules() //delete PDRs/FAR
			t.pathIdGen.Free(path.id)
		} //fire an warning if it is the default path
	}
}

func (t *Tunnel) isDefaultPath(p *Path) bool {
	if t != nil && t.defaultPath != nil {
		return p.id == t.defaultPath.id

	}
	return false
}

func (t *Tunnel) updatePccRule(rule *models.PccRule) (err error) {
	if _, ok := t.paths[rule.PccRuleId]; ok {
		//update an existing path
		//TODO: simplest solution is to delete this path then create a new one
		err = fmt.Errorf("Update existing PccRule not handled yet")
		return
	} else {
		//create a new data path
		var upfPath topo.UpfPath
		//1. Find Upf Path
		if upfPath, err = t.findUpfPath(rule.RefTcData); err != nil {
			err = utils.WrapError("Find UPF path", err)
			return
		}

		var path *Path
		//2. create data path
		if path, err = t.createPath(upfPath); err != nil {
			err = utils.WrapError("Build UPF path", err)
		}
		t.setPcc(path, rule)
		t.paths[rule.PccRuleId] = path

		t.Infof("Data path %d is created for Pcc rule %s", path.id, rule.PccRuleId)
	}
	return
}

//send PfcpSessionEstablishment/PfcpSessionModification toward UPFs in the
//datapaths
func (t *Tunnel) updateUPFs(sessions map[string]*dataplane.PfcpSession) (err error) {
	t.Tracef("Update Pfcp sessions")
	if len(sessions) == 0 { //if the list is empty, take all sessions
		sessions = t.sessions
	}

	l := len(sessions)
	errCh := make(chan error, l)

	worker := dataplane.Worker()
	for _, s := range sessions {
		worker.Go(func() {
			errCh <- s.Update()
		})
	}

	for i := 0; i < l; i++ {
		if err = <-errCh; err != nil {
			err = utils.WrapError("Update pfcp sesion [first encounter error]", err)
			return
		}
	}

	return
}
