type Tunnel struct {
	*logrus.Entry
	ctx              dataplane.SmContext
	ranTransportNets []string

	paths       map[string]*Path        //all data-paths with PCC rules assigned by PCF
	defaultPath *Path                   //default data path (default Qos flow)
	cachedPaths map[string]topo.UpfPath //cached found UPF paths by query IDs

	ranIp   net.IP
	ranTeid uint32

	sessionRules        map[string]*models.SessionRule //from PCF
	selectedSessionRule string                         //selected session rule (to build default qos flow)

	qfiGen                idgen.Generator[uint8] //qos flow identity generator
	qosFlows              map[string]*QosFlow    //all qos flows indexed by qos ID generated by PCF
	trafficControlDataMap map[string]models.TrafficControlData

	sessions  map[string]*dataplane.PfcpSession //map upf id to its session
	pathIdGen idgen.Generator[uint8]            //path id generator
}

func CreateTunnel(ctx dataplane.SmContext, ranTransportNets []string) *Tunnel {
	t := &Tunnel{
		ctx: ctx,
		Entry: ctx.WithFields(logrus.Fields{
			"mod": "tunnel",
		}),
		ranTransportNets: make([]string, len(ranTransportNets)),
		qfiGen:           idgen.NewGenerator[uint8](2, math.MaxUint8), //1 is reserved for default Qos flow
		paths:            make(map[string]*Path),
		qosFlows:         make(map[string]*QosFlow),
		sessionRules:     make(map[string]*models.SessionRule),
		sessions:         make(map[string]*dataplane.PfcpSession),
		cachedPaths:      make(map[string]topo.UpfPath),
		pathIdGen:        idgen.NewGenerator[uint8](1, math.MaxUint8),
	}
	copy(t.ranTransportNets, ranTransportNets)
	return t
}

//get an existing session at a Upf or create a new one for the tunnel
func (t *Tunnel) getPfcpSession(upf *dataplane.Upf) (session *dataplane.PfcpSession, err error) {
	upfId := upf.Id()
	if s, ok := t.sessions[upfId]; ok {
		session = s
		return
	}
	if session, err = upf.CreateSession(t.ctx.(dataplane.SmContext)); err == nil {
		t.sessions[upfId] = session
	}
	return
}

//check if the tunnel can conntect to a gnB (in case of path switch)
func (t *Tunnel) IsConnectedToRan(nets []string) bool {
	//all data paths much be reachable
	for _, p := range t.getAllPaths() {
		if !p.isReachable(nets) {
			return false
		}
	}
	return true
}

//disconnect from RAN
func (t *Tunnel) DisconnectRan() (err error) {
	sessions := make(map[string]*dataplane.PfcpSession)
	for _, p := range t.getAllPaths() {
		anNode := p.nodes[0]
		anNode.downlink.DeactivateFAR(p.id)
		sessions[anNode.session.GetUpfId()] = anNode.session
	}
	if err = t.updateUPFs(sessions); err != nil {
		err = utils.WrapError("Update sessions at UPFs", err)
	}
	return
}

// Once receive IP and TEID from RAN, update the forwarding rule for the first
// UPF so that it can forward downlink packets toward gnB
func (t *Tunnel) UpdateRanInfo(ip net.IP, teid uint32) (err error) {

	t.ranIp = ip
	t.ranTeid = teid

	sessions := make(map[string]*dataplane.PfcpSession)
	for _, path := range t.getAllPaths() {
		//the first UPF (connecting to gnB)
		anNode := path.nodes[0] //must not be nil
		link := anNode.downlink
		link.UpdateFAR(path.id, ip, teid)
		sessions[anNode.session.GetUpfId()] = anNode.session
	}
	if err = t.updateUPFs(sessions); err != nil {
		err = utils.WrapError("Update sessions at UPFs", err)
	} else {
		t.Infof("Tunnel is updated with gnB information [ip = %s, teid = %d]", ip.String(), teid)
	}
	return
}

func (t *Tunnel) getAllPaths() (all []*Path) {
	hasDefault := false
	for _, p := range t.paths {
		hasDefault = t.isDefaultPath(p)
		all = append(all, p)
	}
	if !hasDefault && t.defaultPath != nil {
		all = append(all, t.defaultPath)
	}
	return
}

func (t *Tunnel) Release() (err error) {
	//1. remove all rules from UPFs
	for _, path := range t.getAllPaths() {
		path.deleteRules()
	}
	//2. ask UPFs to release sessions
	for _, s := range t.sessions {
		s.Release()
	}
	return
}

