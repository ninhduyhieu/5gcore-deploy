func (p *Path) buildQosRule(isDefault bool) QosRule {
	p.Debugf("Build Qos rule for path %d", p.id)
	rule := QosRule{
		Identifier:    p.qosFlow.qfi,
		QFI:           p.qosFlow.qfi,
		OperationCode: OperationCodeCreateNewQosRule,
	}
	rule.Precedence = uint8(p.precedence)
	if isDefault {
		rule.PacketFilterList = []PacketFilter{
			{
				Identifier:    1,
				Direction:     PacketFilterDirectionBidirectional,
				ComponentType: PacketFilterComponentTypeMatchAll,
			}}
		rule.DQR = 0x01
	} else {
		rule.PacketFilterList = p.buildPacketFilters()
	}
	return rule
}

func (p *Path) buildQosFlowDesc() QosFlowDesc {
	p.Debugf("Build Qos flow desc for path %d", p.id)
	return p.qosFlow.converter.toNasQosFlowDesc(p.qosFlow.qfi)
}

func (p *Path) buildNgapQosFlowSetupRequestItem() ies.QosFlowSetupRequestItem {
	return p.qosFlow.converter.toNgapQosFlowSetupRequestItem(p.qosFlow.qfi)
}

//check if the first UPF can connect to the gnb's transport network
func (p *Path) isReachable(nets []string) bool {
	return p.nodes[0].session.GetUpf().IsReachable(nets)
}
