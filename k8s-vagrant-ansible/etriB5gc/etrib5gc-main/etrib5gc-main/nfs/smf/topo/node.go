func (node *UpfNode) String() string {
	var b bytes.Buffer
	b.WriteString(fmt.Sprintf("id=%s", node.id))

	infs := []string{}
	for netname, items := range node.infs {
		ips := []string{}
		for _, item := range items {
			ips = append(ips, item.ip.String())
		}
		infs = append(infs, fmt.Sprintf("%s:%s", netname, strings.Join(ips, "/")))
	}
	if len(infs) > 0 {
		b.WriteString(";\tinfs = " + strings.Join(infs, ", "))
	}

	return b.String()
}
